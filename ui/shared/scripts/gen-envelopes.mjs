// Generate envelopes.gen.d.ts from `bcn schema <tool>`, so the UI's types come from the
// CLI rather than from guesses. Run after changing an envelope in bcn:
//   npm run gen:envelopes            (uses tooling/.venv/bin/bcn, or $BCN)
import { execFileSync } from 'node:child_process';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..', '..');
const bcn = process.env.BCN || join(repo, 'tooling', '.venv', 'bin', 'bcn');
if (!existsSync(bcn)) throw new Error(`bcn not found at ${bcn}; run scripts/setup.sh or set BCN`);

const TOOLS = ['status', 'show', 'diagnostics', 'sync', 'review', 'doctor', 'codes', 'intake', 'translation', 'edit',
  'validate', 'render', 'cues', 'subtitles', 'package', 'qa', 'ack', 'script', 'bumpers', 'compose'];
const pascal = (s) => s.replace(/(^|_)(\w)/g, (_, __, c) => c.toUpperCase());

let out = '// Generated by shared/scripts/gen-envelopes.mjs from `bcn schema`. Do not edit.\n\n';
for (const tool of TOOLS) {
  const env = JSON.parse(execFileSync(bcn, ['schema', tool, '--quiet'], { encoding: 'utf8' }));
  const schema = env.json_schema;
  if (!schema) throw new Error(`bcn schema ${tool} returned no json_schema`);
  const ts = await compile(schema, `${pascal(tool)}Envelope`, {
    bannerComment: '', additionalProperties: false, declareExternallyReferenced: true, strictIndexSignatures: false,
    style: { singleQuote: true },
  });
  out += `// -- bcn ${tool} ${'-'.repeat(70 - tool.length)}\n${ts.replace(/^export /gm, 'export ')}\n`;
}
writeFileSync(join(here, '..', 'envelopes.gen.d.ts'), out);
console.log(`wrote envelopes.gen.d.ts (${TOOLS.length} envelopes)`);
